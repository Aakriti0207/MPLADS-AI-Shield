/**
 * Shared, pure display model for the Risk Fusion + Explainable AI UI.
 *
 * ============================================================================
 * THE ONE RULE THIS FILE EXISTS TO ENFORCE
 * ============================================================================
 * The backend is the single source of truth for every risk number. Nothing in
 * this file computes, re-weights, or re-derives a risk score. It only:
 *
 *   - reshapes `GET /projects/:id/risk` into an array the UI can map over,
 *   - computes DISPLAY-ONLY ratios (share of final risk, bar widths),
 *   - reports whether the backend's own numbers reconcile.
 *
 * Three distinct quantities are kept strictly separate everywhere, because
 * conflating them is the single easiest way to make an explanation wrong:
 *
 *   rawScore     -- the component's own 0-100 detector score.
 *   weight       -- the component's configured point cap out of 100
 *                   (ml/risk_config.py RISK_COMPONENT_CAPS). Because the caps
 *                   sum to exactly 100, the cap in points equals the weight in
 *                   percent -- that is a property of the config, not an
 *                   assumption made here.
 *   contribution -- the points this component actually added to the final
 *                   score. By the backend's construction,
 *                   rawScore * weight / 100 === contribution.
 *   sharePct     -- DISPLAY ONLY: contribution / total contribution. This is
 *                   the only number this file invents, and it never feeds back
 *                   into the score.
 */

